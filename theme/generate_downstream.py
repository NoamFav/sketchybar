def patch_ls_colors(colors, config_root):
    """Patch EZA_COLORS / LS_COLORS in zsh/exports/paths.zsh — these
    duplicate eza's filekinds: roles as raw ANSI RGB, used by zsh's
    completion listing and anything else that reads $LS_COLORS. Per-
    extension entries inside LS_COLORS are left untouched (same reasoning
    as file_type:/extensions: in eza's theme.yml).
    """
    path = os.path.join(config_root, "zsh", "exports", "paths.zsh")
    with open(path) as f:
        text = f.read()

    role_map = {
        "di": colors["accent"],
        "ln": colors["blue"],
        "ex": colors["green"],
        "pi": colors["bg2"],
        "so": colors["bg2"],
        "bd": colors["yellow"],
        "cd": colors["yellow"],
        "or": colors["red"],
    }
    for key, hex_value in role_map.items():
        h = hex_value.lstrip("#")
        rgb = f"{int(h[0:2], 16)};{int(h[2:4], 16)};{int(h[4:6], 16)}"
        # Lookbehind requires the key to start right after a ':' or the
        # opening '"' — excludes e.g. "*.tex=" / "*.ex=" extension entries,
        # which only share the trailing "ex=" substring, not the boundary.
        text = re.sub(rf'(?<=[:"]){key}=38;2;\d+;\d+;\d+', f'{key}=38;2;{rgb}', text)

    with open(path, "w") as f:
        f.write(text)
    print(f"Patched: {path}")


def patch_omp(colors, config_root):
    path = os.path.join(config_root, "zsh", "external", "oh-my-posh", "default.json")
    with open(path) as f:
        text = f.read()

    # path uses the accent (matches eza's directory color), username uses blue.
    patches = {
        "blue": colors["accent"],
        "cyan": colors["blue"],
        "green": colors["green"],
        "purple": colors["magenta"],
        "red": colors["red"],
        "yellow": colors["yellow"],
        "comment": colors["grey"],
    }
    for key, value in patches.items():
        text, _ = re.subn(
            rf'^(    "{re.escape(key)}": )"#[0-9a-fA-F]{{6}}"(,?)$',
            rf'\g<1>"{value}"\g<2>',
            text, count=1, flags=re.MULTILINE,
        )

    with open(path, "w") as f:
        f.write(text)
    print(f"Patched: {path}")


def main(config_root):
    colors = load_colors()
    write_ghostty(colors, config_root)
    write_atuin(colors, config_root)
    patch_yazi(colors, config_root)
    patch_eza(colors, config_root)
    patch_ls_colors(colors, config_root)
    patch_omp(colors, config_root)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print("Usage: generate_downstream.py config_root", file=sys.stderr)
        sys.exit(1)
    main(sys.argv[1])
