def patch_ls_colors(colors, config_root):
    """Patch EZA_COLORS / LS_COLORS in zsh/exports/paths.zsh — these
    duplicate eza's filekinds: roles as raw ANSI RGB, used by zsh's
    completion listing and anything else that reads $LS_COLORS. Per-
    extension entries inside LS_COLORS are left untouched (same reasoning
    as file_type:/extensions: in eza's theme.yml).
    """
    path = os.path.join(config_root, "zsh", "exports", "paths.zsh")
    with open(path) as f:
        text = f.read()

    role_map = {
        "di": colors["accent"],
        "ln": colors["blue"],
        "ex": colors["green"],
        "pi": colors["bg2"],
        "so": colors["bg2"],
        "bd": colors["yellow"],
        "cd": colors["yellow"],
        "or": colors["red"],
    }
    for key, hex_value in role_map.items():
        h = hex_value.lstrip("#")
        rgb = f"{int(h[0:2], 16)};{int(h[2:4], 16)};{int(h[4:6], 16)}"
        # Lookbehind requires the key to start right after a ':' or the
        # opening '"' — excludes e.g. "*.tex=" / "*.ex=" extension entries,
        # which only share the trailing "ex=" substring, not the boundary.
        text = re.sub(rf'(?<=[:"]){key}=38;2;\d+;\d+;\d+', f'{key}=38;2;{rgb}', text)

    with open(path, "w") as f:
        f.write(text)
    print(f"Patched: {path}")


def write_nvim_colors(colors, config_root):
    """Derive a tokyonight.nvim-shaped palette (same field names/structure)
    from the wallpaper colors, so nvim/colors/wallpaper.lua's hand-written
    highlight groups — and lualine.lua's `require("colors_generated")` —
    have every field tokyonight's own palette would have, without needing
    tokyonight installed or active.
    """
    out = os.path.join(config_root, "nvim", "lua", "colors_generated.lua")
    ts = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    bg = colors["black"]
    fg = colors["white"]
    grey = colors["grey"]
    red, orange, yellow = colors["red"], colors["orange"], colors["yellow"]
    green, blue, magenta = colors["green"], colors["blue"], colors["magenta"]
    accent, bg1, bg2 = colors["accent"], colors["bg1"], colors["bg2"]

    bg_dark = darken(bg, 0.03)
    bg_dark1 = darken(bg, 0.05)
    bg_highlight = bg1
    fg_dark = blend(fg, grey, 0.5)
    fg_gutter = blend(grey, bg_highlight, 0.5)
    comment = grey
    dark3 = grey
    dark5 = lighten(grey, 0.25)

    red1 = darken(red, 0.12)
    green1 = lighten(green, 0.15)
    green2 = darken(green, 0.08)
    blue0 = darken(blue, 0.22)
    blue1 = accent
    # blend toward fg (not accent): accent is near-complementary to blue on
    # this wallpaper, so blending the two averages toward a muddy grey.
    blue2 = blend(blue, fg, 0.25)
    blue5 = lighten(blue, 0.28)
    blue6 = lighten(blue, 0.42)
    blue7 = darken(blue, 0.32)
    cyan = blue  # no real cyan in the wallpaper palette
    teal = blend(green, blue, 0.5)
    magenta2 = blend(magenta, red, 0.4)
    purple = blend(magenta, blue, 0.3)

    terminal_black = bg2
    black = blend(bg, "#000000", 0.15)
    border = black
    border_highlight = blend(bg, blue1, 0.8)

    bg_popup = bg_highlight
    bg_statusline = bg_dark
    bg_visual = blend(bg, blue0, 0.4)
    bg_search = blue0
    fg_sidebar = fg_dark
    fg_float = fg

    diff_add = blend(bg, green2, 0.25)
    diff_delete = blend(bg, red1, 0.25)
    diff_change = blend(bg, blue7, 0.15)
    diff_text = blue7

    lines = [
        "-- Auto-generated by sketchybar/theme/generate.sh — do not edit manually",
        f"-- Generated: {ts}",
        "-- Shaped like tokyonight.nvim's Palette (see :h tokyonight) so",
        "-- nvim/colors/wallpaper.lua and lualine.lua can consume it directly.",
        "return {",
        f'  bg = "{bg}",',
        f'  bg_dark = "{bg_dark}",',
        f'  bg_dark1 = "{bg_dark1}",',
        f'  bg_highlight = "{bg_highlight}",',
        f'  bg_popup = "{bg_popup}",',
        f'  bg_statusline = "{bg_statusline}",',
        f'  bg_sidebar = "NONE",',
        f'  bg_float = "NONE",',
        f'  bg_visual = "{bg_visual}",',
        f'  bg_search = "{bg_search}",',
        f'  fg = "{fg}",',
        f'  fg_dark = "{fg_dark}",',
        f'  fg_gutter = "{fg_gutter}",',
        f'  fg_sidebar = "{fg_sidebar}",',
        f'  fg_float = "{fg_float}",',
        f'  comment = "{comment}",',
        f'  dark3 = "{dark3}",',
        f'  dark5 = "{dark5}",',
        f'  black = "{black}",',
        f'  border = "{border}",',
        f'  border_highlight = "{border_highlight}",',
        f'  terminal_black = "{terminal_black}",',
        f'  none = "NONE",',
        "",
        f'  red = "{red}",',
        f'  red1 = "{red1}",',
        f'  orange = "{orange}",',
        f'  yellow = "{yellow}",',
        f'  green = "{green}",',
        f'  green1 = "{green1}",',
        f'  green2 = "{green2}",',
        f'  blue = "{blue}",',
        f'  blue0 = "{blue0}",',
        f'  blue1 = "{blue1}",',
        f'  blue2 = "{blue2}",',
        f'  blue5 = "{blue5}",',
        f'  blue6 = "{blue6}",',
        f'  blue7 = "{blue7}",',
        f'  cyan = "{cyan}",',
        f'  teal = "{teal}",',
        f'  magenta = "{magenta}",',
        f'  magenta2 = "{magenta2}",',
        f'  purple = "{purple}",',
        "",
        f'  error = "{red1}",',
        f'  warning = "{yellow}",',
        f'  info = "{blue2}",',
        f'  hint = "{teal}",',
        f'  todo = "{blue}",',
        "",
        "  git = {",
        f'    add = "{green}",',
        f'    change = "{blue}",',
        f'    delete = "{red}",',
        f'    ignore = "{dark3}",',
        "  },",
        "  diff = {",
        f'    add = "{diff_add}",',
        f'    delete = "{diff_delete}",',
        f'    change = "{diff_change}",',
        f'    text = "{diff_text}",',
        "  },",
        "  rainbow = {",
        f'    "{blue}", "{yellow}", "{green}", "{teal}",',
        f'    "{magenta}", "{purple}", "{orange}", "{red}",',
        "  },",
        "  terminal = {",
        f'    black = "{black}", black_bright = "{terminal_black}",',
        f'    red = "{red}", red_bright = "{brighten(red)}",',
        f'    green = "{green}", green_bright = "{brighten(green)}",',
        f'    yellow = "{yellow}", yellow_bright = "{brighten(yellow)}",',
        f'    blue = "{blue}", blue_bright = "{brighten(blue)}",',
        f'    magenta = "{magenta}", magenta_bright = "{brighten(magenta)}",',
        f'    cyan = "{cyan}", cyan_bright = "{brighten(cyan)}",',
        f'    white = "{fg_dark}", white_bright = "{fg}",',
        "  },",
        "}",
    ]

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Generated: {out}")


def patch_omp(colors, config_root):
    path = os.path.join(config_root, "zsh", "external", "oh-my-posh", "default.json")
    with open(path) as f:
        text = f.read()

    # path uses the accent (matches eza's directory color), username uses blue.
    patches = {
        "blue": colors["accent"],
        "cyan": colors["blue"],
        "green": colors["green"],
        "purple": colors["magenta"],
        "red": colors["red"],
        "yellow": colors["yellow"],
        "comment": colors["grey"],
    }
    for key, value in patches.items():
        text, _ = re.subn(
            rf'^(    "{re.escape(key)}": )"#[0-9a-fA-F]{{6}}"(,?)$',
            rf'\g<1>"{value}"\g<2>',
            text, count=1, flags=re.MULTILINE,
        )

    with open(path, "w") as f:
        f.write(text)
    print(f"Patched: {path}")


def main(config_root):
    colors = load_colors()
    write_ghostty(colors, config_root)
    write_atuin(colors, config_root)
    patch_yazi(colors, config_root)
    patch_eza(colors, config_root)
    patch_ls_colors(colors, config_root)
    write_nvim_colors(colors, config_root)
    patch_omp(colors, config_root)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print("Usage: generate_downstream.py config_root", file=sys.stderr)
        sys.exit(1)
    main(sys.argv[1])
