def replace_in_section(text, section, key, new_value):
    """Replace `key = ...` with `key = new_value`, scoped to one [section]."""
    sec_match = re.search(rf'^\[{re.escape(section)}\]$', text, re.MULTILINE)
    if not sec_match:
        return text
    start = sec_match.end()
    next_header = re.search(r'^\[', text[start:], re.MULTILINE)
    end = start + next_header.start() if next_header else len(text)
    block = text[start:end]
    block, n = re.subn(
        rf'^{re.escape(key)} = .*$', f'{key} = {new_value}', block,
        count=1, flags=re.MULTILINE,
    )
    if n == 0:
        return text
    return text[:start] + block + text[end:]


def patch_yazi(colors, config_root):
    path = os.path.join(config_root, "yazi", "theme.toml")
    with open(path) as f:
        text = f.read()

    accent, red, grey = colors["accent"], colors["red"], colors["grey"]
    white, black, green, yellow = colors["white"], colors["black"], colors["green"], colors["yellow"]

    patches = [
        ("mgr", "cwd", f'{{ fg = "{accent}" }}'),
        ("mgr", "count_copied", f'{{ fg = "{white}", bg = "{green}" }}'),
        ("mgr", "count_cut", f'{{ fg = "{white}", bg = "{red}" }}'),
        ("mgr", "count_selected", f'{{ fg = "{black}", bg = "{yellow}" }}'),
        ("mgr", "border_style", f'{{ fg = "{grey}" }}'),
        ("tabs", "active", f'{{ bg = "{accent}", bold = true }}'),
        ("tabs", "inactive", f'{{ fg = "{accent}", bg = "{grey}" }}'),
        ("mode", "normal_main", f'{{ bg = "{accent}", bold = true }}'),
        ("mode", "normal_alt", f'{{ fg = "{accent}", bg = "{grey}" }}'),
        ("mode", "select_main", f'{{ bg = "{red}", bold = true }}'),
        ("mode", "select_alt", f'{{ fg = "{red}", bg = "{grey}" }}'),
        ("mode", "unset_main", f'{{ bg = "{red}", bold = true }}'),
        ("mode", "unset_alt", f'{{ fg = "{red}", bg = "{grey}" }}'),
    ]
    for section, key, value in patches:
        text = replace_in_section(text, section, key, value)

    with open(path, "w") as f:
        f.write(text)
    print(f"Patched: {path}")


def replace_yaml_key(text, key, new_hex, section=None):
    """Replace `key: { foreground: "..." }` with new_hex.

    If section is given, scope to the `section:` block (2-space-indented
    children, up to the next zero-indent key or EOF) — needed because some
    key names (e.g. "normal") appear under more than one section with
    different intended colors. If section is None, match a zero-indent
    top-level key instead.
    """
    if section is None:
        text, _ = re.subn(
            rf'^({re.escape(key)}: {{ foreground: )"[^"]*"( }})$',
            rf'\g<1>"{new_hex}"\g<2>',
            text, count=1, flags=re.MULTILINE,
        )
        return text

    sec_match = re.search(rf'^{re.escape(section)}:$', text, re.MULTILINE)
    if not sec_match:
        return text
    start = sec_match.end()
    next_top = re.search(r'^\S', text[start:], re.MULTILINE)
    end = start + next_top.start() if next_top else len(text)
    block = text[start:end]
    block, n = re.subn(
        rf'^(  {re.escape(key)}: {{ foreground: )"[^"]*"( }})$',
        rf'\g<1>"{new_hex}"\g<2>',
        block, count=1, flags=re.MULTILINE,
    )
    if n == 0:
        return text
    return text[:start] + block + text[end:]


